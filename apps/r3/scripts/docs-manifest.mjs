/* Bundles content/docs/**.mdx into lib/docs-manifest.json so the Worker
   never reads the filesystem at request time: lib/mdx.ts imports the
   manifest instead of calling readdirSync/readFileSync, which threw
   "no such file or directory, readdir '/bundle/content/docs'" in
   production. Same pattern as apps/garden/scripts/content-manifest.mjs.
   The manifest is committed and regenerated by prebuild;
   scripts/docs-manifest.test.mjs guards freshness. */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(fileURLToPath(new URL(".", import.meta.url)), "..");

function scanFiles(dir, base) {
  const results = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith(".")) continue;
    if (entry.isDirectory()) {
      results.push(...scanFiles(path.join(dir, entry.name), base));
    } else if (entry.isFile() && entry.name.endsWith(".mdx")) {
      // POSIX separators: keys become doc slugs once ".mdx" is stripped.
      results.push(path.relative(base, path.join(dir, entry.name)).split(path.sep).join("/"));
    }
  }
  return results;
}

export function buildManifest(appRoot = root) {
  const docsDir = path.join(appRoot, "content/docs");
  const files = {};
  for (const relative of scanFiles(docsDir, docsDir).sort()) {
    files[relative] = readFileSync(path.join(docsDir, relative), "utf8");
  }
  return { files };
}

export const manifestPath = path.join(root, "lib/docs-manifest.json");

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const manifest = buildManifest();
  writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + "\n");
  console.log(`docs-manifest.json: ${Object.keys(manifest.files).length} docs`);
}
